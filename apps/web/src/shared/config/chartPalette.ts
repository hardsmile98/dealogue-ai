/**
 * Категориальная палитра для серий на графиках. Порядок фиксированный —
 * он проверен на различимость соседних цветов, в том числе при нарушениях
 * цветовосприятия, поэтому серии получают цвета строго по индексу слота,
 * без перетасовки. Больше 8 серий не заводим — хвост сворачиваем в «Другие».
 */
export const CHART_SERIES_COLORS = [
  '#2a78d6', // blue
  '#eb6834', // orange
  '#1baf7a', // aqua
  '#eda100', // yellow
  '#e87ba4', // magenta
  '#008300', // green
  '#4a3aa7', // violet
  '#e34948', // red
] as const;

/** Нейтральный серый для «фоновой» серии (например, «без кода»). */
export const CHART_NEUTRAL_COLOR = '#b9b8b0';

/**
 * Цвет слота по индексу. За пределами палитры — нейтральный серый: серия
 * останется читаемой, даже если вызывающий код попросит больше слотов,
 * чем есть цветов.
 */
export function chartSeriesColor(index: number): string {
  return CHART_SERIES_COLORS[index] ?? CHART_NEUTRAL_COLOR;
}
