/**
 * Категориальная палитра для серий на графиках. Порядок фиксированный —
 * он проверен на различимость соседних цветов, в том числе при нарушениях
 * цветовосприятия, поэтому серии получают цвета строго по индексу слота,
 * без перетасовки. Первые 8 — основная палитра; слоты 9–15 добавлены для
 * статистики по кодам и проверены только для соседних серий: несоседние
 * цвета (например, aqua и teal) различаются хуже, поэтому рядом с графиком
 * всегда нужна таблица. Больше 15 серий не заводим — хвост сворачиваем
 * в «Остальные».
 */
export const CHART_SERIES_COLORS = [
  '#2a78d6', // blue
  '#eb6834', // orange
  '#1baf7a', // aqua
  '#eda100', // yellow
  '#e87ba4', // magenta
  '#008300', // green
  '#4a3aa7', // violet
  '#e34948', // red
  '#2aa6c4', // cyan
  '#8e3b6e', // plum
  '#7f9a00', // olive
  '#1d4f9e', // navy
  '#a0662a', // brown
  '#9b3fb5', // orchid
  '#00897b', // teal
] as const;

/** Нейтральный серый для «фоновой» серии (например, «без кода»). */
export const CHART_NEUTRAL_COLOR = '#b9b8b0';

/**
 * Тёмный нейтральный — для сводной серии «Остальные». Отличается от
 * CHART_NEUTRAL_COLOR настолько, что обе серии различимы в одном столбце.
 */
export const CHART_OTHER_COLOR = '#7c7b75';

/**
 * Цвет слота по индексу. За пределами палитры — нейтральный серый: серия
 * останется читаемой, даже если вызывающий код попросит больше слотов,
 * чем есть цветов.
 */
export function chartSeriesColor(index: number): string {
  return CHART_SERIES_COLORS[index] ?? CHART_NEUTRAL_COLOR;
}
