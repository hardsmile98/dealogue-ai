import type { HistoryLine } from '../core/history.js';
import type { IncomingMessage, Memory, Plan } from '../core/types.js';
import type { LlmMessage } from '../llm/llm.types.js';
import type { Stage } from '../library/kinds.js';
import type { Persona } from '../library/persona.js';
import {
  aboutBlock,
  blockPreview,
  examplesBlock,
  historyBlock,
  memoryBlock,
  personaBlock,
  turnBlock,
} from './blocks.js';
import type { ExampleSample, LibrarySample } from './blocks.js';

const STAGE_NOTES: Record<Stage, string> = {
  intake:
    'Этап: знакомство. Клиент пришёл за бесплатным раскладом. Ты собираешь дату и место рождения и сферу запроса, чтобы сделать анализ.',
  links:
    'Этап: ожидание диагностики. Ты уже сказал, что делаешь анализ и вернёшься с результатами. Диагностику не пересказываешь и не раскрываешь.',
  diagnostic:
    'Этап: диагностика отправлена. Ты ждёшь отклика. О практиках подробно не рассказываешь, пока система не отправит их описание.',
  offer:
    'Этап: описание практик отправлено. Отвечаешь на вопросы о практиках по разделу «о себе и о работе». Цены называешь только через веху «стоимость», не своими словами.',
  prices: 'Этап: цены отправлены. Дальше отвечает менеджер.',
};

const RULES = `Правила:
1. Пиши только то, что есть в плане хода: ответы на перечисленные пункты и шаг воронки. Больше ничего. Если пункта нет в плане, на него не отвечай — присланные данные, «ок», просьбу о раскладе и рассказ о проблеме уже закрывает шаг воронки.
2. Шаг воронки пиши по фразе из сценария: её смысл и её вопрос, похожая длина. Подстроить под разговор можно (обращение, связка с ответом), добавлять свои мысли, обещания и вопросы — нельзя. Если план говорит, что шаг — утверждение, вопросов в нём нет совсем (даже «хорошо?» из фразы). Если фраза на другом языке, чем у клиента, переведи её.
3. Ответ на пункт — одна-две фразы по существу, без вступлений.
4. Запрещено: задавать вопросы, кроме вопроса из шага воронки; подтверждать полученное («записал», «принял», «отлично, всё есть» — короткое «спасибо» можно); анонсировать свои действия («берусь за карту», «смотрю под ваш запрос»), если это не шаг воронки; оценивать и пересказывать слова клиента («это важная деталь», «хорошо, что вы это озвучили», «вы написали, что…»); писать о вехе, которую отправит система, — ни вступления, ни пересказа, ни продолжения после неё.
5. Пиши как человек в мессенджере: коротко, тепло, от первого лица, на «вы», о себе — строго в роде из образа. Без списков, заголовков и канцелярита, эмодзи изредка. Не представляйся и не рассказывай биографию, если этого нет в шаге и не спросили.
6. Ничего не выдумывай: факты о клиенте — только из памяти и его сообщений; факты о себе и о практике — только из образа и раздела «о себе и о работе»; цены, суммы, сроки, ссылки — никогда своими словами. Если спрашивают о том, чего в образе нет, ответь общо.
7. Отвечай на языке клиента, указанном в плане. Порядок: приветствие (если план просит), ответы, шаг воронки.

Формат ответа — один JSON-объект:
{"messages": ["сообщение клиенту", "…"], "notes": "одно предложение: что сделал и почему"}
- messages — отдельные сообщения в Telegram по порядку: одно на ответы, одно на шаг воронки. Внутри сообщения можно переносить строки. Только живой текст для клиента: без пометок, кавычек-цитат и служебных слов.`;

export interface WriterPromptInput {
  persona: Persona;
  stage: Stage;
  examples: readonly ExampleSample[];
  about: readonly LibrarySample[];
  history: readonly HistoryLine[];
  memory: Memory;
  plan: Plan;
  messages: readonly IncomingMessage[];
  /** Тело вехи хода: ответчик видит его начало, чтобы не повторять его смысл. */
  block?: string | null;
  /** Замечания проверяющего к прошлой версии — для второй попытки. */
  reviewNotes?: readonly string[];
}

/**
 * Промпт ответчика: статика (образ, правила, этап, примеры) первой — под
 * кэш префикса; история, память, план и ход клиента — в конце. Фразы шага
 * из таблиц приходят в плане.
 */
export function buildWriterPrompt(input: WriterPromptInput): LlmMessage[] {
  const system = [
    `Ты — ${input.persona.name}, энергопрактик. Ты сам переписываешься с клиентом в Telegram и ведёшь его по воронке из своего сценария. Пишешь от первого лица, как живой человек, а не ассистент.`,
    '',
    '## Образ',
    personaBlock(input.persona),
    '',
    '## О себе и о работе (единственный источник фактов о практике)',
    aboutBlock(input.about),
    '',
    RULES,
    '',
    STAGE_NOTES[input.stage],
  ];
  const examples = examplesBlock(input.examples);
  if (examples)
    system.push(
      '',
      '## Примеры реальных диалогов на этом этапе (тон и длина)',
      examples,
    );

  const { constraints } = input.plan;
  const user = [
    '## История переписки',
    historyBlock(input.history),
    '',
    '## Что известно о клиенте',
    memoryBlock(input.memory),
    '',
    '## План этого хода',
    input.plan.goal,
    `Язык ответа: ${constraints.language}. Сообщений не больше ${constraints.maxParts}.`,
    ...(input.block && input.plan.afterBlock
      ? [
          '',
          '## Текст вехи, который система отправит перед твоими сообщениями (конец)',
          `«${blockPreview(input.block, 'end')}»`,
          'Не повторяй его смысл и слова и не комментируй его.',
        ]
      : input.block
        ? [
            '',
            '## Текст вехи, который система отправит сразу после твоих сообщений (начало)',
            `«${blockPreview(input.block)}»`,
            'Не повторяй его смысл и слова и не предваряй его.',
          ]
        : []),
    '',
    '## Новые сообщения клиента',
    turnBlock(input.messages),
  ];
  if (input.reviewNotes && input.reviewNotes.length > 0) {
    user.push(
      '',
      '## Замечания к прошлой версии ответа (исправь их, остальное сохрани)',
      ...input.reviewNotes.map((note) => `- ${note}`),
    );
  }
  user.push('', 'Напиши ответ.');
  return [
    { role: 'system', content: system.join('\n') },
    { role: 'user', content: user.join('\n') },
  ];
}
