import type { HistoryLine } from '../core/history.js';
import type { IncomingMessage, Memory } from '../core/types.js';
import type { LlmMessage } from '../llm/llm.types.js';
import { LANGUAGES, OBJECTION_CATEGORIES } from '../library/kinds.js';
import { categoriesBlock, historyBlock, memoryBlock, turnBlock } from './blocks.js';

/** Сколько последних сообщений истории видит анализатор. */
export const ANALYZER_HISTORY = 10;

const SYSTEM = `Ты — аналитик переписки энергопрактика с клиентом в Telegram. Ты не пишешь клиенту. Твоя задача — извлечь факты и понять, чего клиент хочет в новых сообщениях. Отвечай строго одним JSON-объектом без пояснений.

Поля ответа:
- "card": обновления карточки клиента по новым сообщениям. Каждое поле — объект {"value": …, "confidence": 0..1}. Поля: "name" (имя клиента, только если он его назвал; не пиши «не указано»), "gender" ("f" или "m": по имени, окончаниям глаголов и прилагательных («я устала», «сама»), по словам о партнёре («муж ушёл» → скорее всего женщина, confidence 0.85; «жена» → мужчина); если признаков нет — не заполняй), "birthDate" (дата рождения как написал клиент), "birthPlace" (место рождения), "category" (ключ категории запроса из списка ниже; если запрос не описан — не заполняй). Не заполняй поля, о которых в новых сообщениях ничего нет.
- "facts": новые факты о клиенте из его слов, короткими фразами в третьем лице: [{"kind": "situation|emotion|objection|biography|preference|expectation", "text": "…", "confidence": 0..1}]. Только то, что клиент сказал сам. Не повторяй факты, которые уже есть в памяти. Коды из рекламы («код 12»), дату и место рождения и просьбу о бесплатном раскладе фактами не считай — они уже в карточке.
- "supersedes": тексты фактов из памяти, которым новые сообщения противоречат (дословно из списка фактов).
- "summary": обновлённое резюме разговора, 5–8 предложений: с чем пришёл, что произошло, что практик обещал, какие вопросы задавал клиент, где сейчас разговор. Обнови старое резюме, не пиши с нуля.
- "language": язык новых сообщений клиента — один из кодов ${LANGUAGES.map((code) => `"${code}"`).join(', ')}; любой другой язык — "other"; null, если по новым сообщениям язык не понять (коротко: «ок», эмодзи, имя, дата, ссылка).
- "risk": список из: "aggression" (агрессия, оскорбления), "crisis" (мысли о самоубийстве, самоповреждении, острое состояние), "wants_human" (просит позвать живого человека или менеджера), "asks_if_bot" (спрашивает, бот ли это или ИИ), "unclear" (сообщения невозможно понять). Пустой список, если ничего из этого нет.
- "intents": намерения клиента в новых сообщениях, список из: "asks_price" (спрашивает цену или стоимость), "asks_practice" (спрашивает, как проходит работа, что такое чистка, что будет), "asks_about_practitioner" (спрашивает о самом практике: где живёт, сколько лет, кто он), "asks_diagnostic_status" (спрашивает, готова ли диагностика, «ну что там»), "shares_story" (рассказывает о своей ситуации), "ready" (готов начать, согласен), "doubts" (сомневается), "objects" (возражает: дорого, не верю, подумаю), "smalltalk" (разговор ни о чём), "answers_question" (отвечает на вопрос практика), "silent_ack" (формальное «ок», «спасибо», «понятно»).
- "objection": категория возражения строго из списка: ${OBJECTION_CATEGORIES.join(', ')} — или null.
- "interest": интерес клиента к работе с практиком, 0 (никакого) … 3 (готов начать).
- "mood": одно из "calm", "sad", "anxious", "skeptical", "irritated".
- "answerPoints": на что в новых сообщениях нужно ответить, по порядку клиента: [{"text": "что именно сказал или спросил, коротко", "kind": "question|fact|request|emotion|other", "topic": "…", "skip": false}]. Несколько сообщений об одном — один пункт; разные темы — разные пункты. Формальное «ок», стикер, «спасибо» — пункт со "skip": true.
  "topic" — о чём пункт: "price" (цена, стоимость, оплата, сколько стоит работа), "practice" (как проходит работа, что за практики, методы, что будет на сессии), "diagnostic" (диагностика или расклад: когда будет, что в ней), "practitioner" (о самом практике: где живёт, сколько лет, как пришёл к практике), "client" (клиент рассказывает о себе, своей ситуации, чувствах), "other" (всё остальное). Вопрос «сколько ждать диагностику» — это "diagnostic", а не "price"; присланные дата и место рождения — "client".

Категории запроса:
${categoriesBlock()}`;

export interface AnalyzerPromptInput {
  memory: Memory;
  history: readonly HistoryLine[];
  messages: readonly IncomingMessage[];
  /** Сколько последних сообщений истории показать; восстановление памяти показывает всё. */
  historyLimit?: number;
}

export function buildAnalyzerPrompt(input: AnalyzerPromptInput): LlmMessage[] {
  const user = [
    '## Память о клиенте',
    memoryBlock(input.memory),
    '',
    '## Последние сообщения переписки',
    historyBlock(input.history.slice(-(input.historyLimit ?? ANALYZER_HISTORY))),
    '',
    '## Новые сообщения клиента (проанализируй их)',
    turnBlock(input.messages),
  ].join('\n');
  return [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: user },
  ];
}
