/**
 * Страховочные эвристики поверх решения модели. Работают по тексту клиента.
 */

// Без \b: в JS-регэкспах граница слова не работает с кириллицей.
const READY_TO_PAY_RE =
  /(оплат[а-я]*|реквизит[а-я]*|сч[её]т[а-я]*|(^|[^а-яё])карт(а|е|у|ы|ой|ою)([^а-яё]|$)|перев[ое]д[а-я]*|куда (платить|скинуть|переводить|отправить деньги)|готов[а]? (купить|оплатить|внести|оформ[а-я]+)|(^|[^а-яё])беру([^а-яё]|$)|покупаю|оформляйте|выставляйте|давайте оформ)/i;

/** Клиент явно просит не писать — дожимы прекращаем. */
const STOP_RE =
  /(не пиш[ии]те|не писать|не звон[ии]те|отпиш[ии]те|отстаньте|хватит писать|не беспокойте|не нужно больше|перестаньте|не актуально|неактуально|спам)/i;

/** Клиент просит человека. */
const HUMAN_RE = /(позов[ии]те|дайте|нужен|хочу|можно)\s+(менеджера|человека|оператора|живого|руководител)/i;

export function looksReadyToPay(clientText: string): boolean {
  return READY_TO_PAY_RE.test(clientText);
}

export function looksLikeStopRequest(clientText: string): boolean {
  return STOP_RE.test(clientText);
}

export function asksForHuman(clientText: string): boolean {
  return HUMAN_RE.test(clientText);
}
